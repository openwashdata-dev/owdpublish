#' Build an R data package from a cleared submission with washr
#'
#' Drives washr 1.1.0 step by step and records what each step did in
#' build/build-log.json. The pipeline wraps washr; it does not fork it.
#'
#' @param id Submission id.
#' @param cleared Directory of cleared submissions.
#' @param packages Directory that holds the built packages.
#' @param name Package name (letters and digits, no separators).
#' @param descriptions Named character vector of variable descriptions.
#' @param org GitHub organisation used in URLs.
#' @param authors A `person` vector for Authors@R. Defaults to the submitter.
#' @param site Build the pkgdown site (slow). Default FALSE in the prototype.
#' @return The package path, invisibly.
owd_build_package <- function(id, cleared = "cleared", packages = "packages", name, descriptions = NULL,
                              org = "openwashdata", authors = NULL, site = FALSE) {
  stopifnot(grepl("^[A-Za-z][A-Za-z0-9]*$", name))
  src <- normalizePath(file.path(cleared, id), mustWork = TRUE)
  m <- read_manifest(src)
  dir.create(packages, showWarnings = FALSE, recursive = TRUE)
  path <- file.path(normalizePath(packages, mustWork = TRUE), name)
  if (dir.exists(path)) unlink(path, recursive = TRUE)
  if (is.null(authors)) {
    parts <- strsplit(m$submitter_name, " ")[[1]]
    authors <- c(utils::person(parts[1], paste(parts[-1], collapse = " "), role = c("aut", "cre"), email = m$contact_email %||% "ghe@mavt.ethz.ch"),
                 utils::person(m$organisation, role = "cph"))
  }
  log <- list()
  step <- function(label, expr) {
    t0 <- Sys.time()
    res <- tryCatch({ force(expr); "ok" }, error = function(e) paste("error:", conditionMessage(e)))
    log[[length(log) + 1]] <<- list(step = label, tool = "washr 1.1.0 via owdpublish", status = res,
                                    seconds = round(as.numeric(difftime(Sys.time(), t0, units = "secs")), 1), at = owd_now())
    message(sprintf("  %-22s %s", label, res))
  }
  old <- options(usethis.quiet = TRUE); on.exit(options(old), add = TRUE)
  step("create_skeleton", create_skeleton(path, name, m, authors, org))
  path <- normalizePath(path, mustWork = TRUE)
  owd <- setwd(path); on.exit(setwd(owd), add = TRUE)
  usethis::proj_set(path, force = TRUE)
  step("setup_ci", washr::setup_ci())
  step("setup_rawdata", washr::setup_rawdata())
  file.copy(file.path(src, "data.csv"), file.path("data-raw", paste0(name, ".csv")), overwrite = TRUE)
  file.copy(file.path(src, "manifest.yml"), file.path("data-raw", "submission.yml"), overwrite = TRUE)
  file.copy(file.path(src, "clearance.json"), file.path("data-raw", "clearance.json"), overwrite = TRUE)
  writeLines(processing_script(name), file.path("data-raw", "data_processing.R"))
  step("data_processing", source(file.path("data-raw", "data_processing.R"), local = new.env()))
  step("setup_dictionary", washr::setup_dictionary())
  step("fill_descriptions", fill_descriptions(descriptions))
  step("setup_roxygen", washr::setup_roxygen())
  step("roxygenise", if (requireNamespace("roxygen2", quietly = TRUE)) roxygen2::roxygenise(".") else stop("roxygen2 not installed"))
  step("update_description", washr::update_description(github_user = sprintf("https://github.com/%s/", org)))
  step("setup_readme", washr::setup_readme(has_example = TRUE))
  step("build_readme", build_readme(path))
  step("update_citation", washr::update_citation(build = FALSE))
  step("update_metadata", washr::update_metadata(quiet = TRUE))
  if (site) step("setup_website", washr::setup_website(has_example = TRUE))
  else step("pkgdown_config", usethis::use_pkgdown())
  write_json_file(log, file.path("build", "build-log.json"))
  writeLines(c("docs", "inst/doc", ".Rproj.user", ".Rhistory", ".DS_Store"), ".gitignore")
  git_commit_all(path, sprintf("build: scaffold %s from submission %s with washr", name, id),
                 c("Assisted-by: owdpublish pipeline (washr 1.1.0, mechanical scaffold)"))
  message("Built ", path)
  invisible(path)
}

`%||%` <- function(a, b) if (is.null(a)) b else a

processing_script <- function(name) c(
  "# Generated by owdpublish: reads the cleared data, types the columns, exports the tidy data.",
  "library(usethis)",
  sprintf("data_in <- utils::read.csv(file.path('data-raw', '%s.csv'), stringsAsFactors = FALSE, check.names = FALSE)", name),
  "for (col in names(data_in)) {",
  "  x <- data_in[[col]]",
  "  if (is.character(x) && all(grepl('^[0-9]{4}-[0-9]{2}-[0-9]{2}$', x[!is.na(x) & x != '']))) data_in[[col]] <- as.Date(x)",
  "}",
  sprintf("%s <- data_in", name),
  sprintf("usethis::use_data(%s, overwrite = TRUE)", name),
  "dir.create(file.path('inst', 'extdata'), showWarnings = FALSE, recursive = TRUE)",
  sprintf("utils::write.csv(%s, file.path('inst', 'extdata', '%s.csv'), row.names = FALSE, na = '')", name, name),
  sprintf("if (requireNamespace('openxlsx', quietly = TRUE)) openxlsx::write.xlsx(%s, file.path('inst', 'extdata', '%s.xlsx'))", name, name)
)

fill_descriptions <- function(descriptions) {
  p <- file.path("data-raw", "dictionary.csv")
  d <- utils::read.csv(p, stringsAsFactors = FALSE, na.strings = c("", "NA"))
  d$description <- ifelse(d$variable_name %in% names(descriptions), unname(descriptions[d$variable_name]), "[to be written by the submitter]")
  utils::write.csv(d, p, row.names = FALSE, na = "")
  invisible(d)
}

build_readme <- function(path) {
  if (requireNamespace("rmarkdown", quietly = TRUE) && requireNamespace("pkgload", quietly = TRUE)) {
    pkgload::load_all(path, quiet = TRUE)
    rmarkdown::render(file.path(path, "README.Rmd"), output_format = rmarkdown::github_document(html_preview = FALSE), quiet = TRUE, envir = new.env())
  } else if (requireNamespace("devtools", quietly = TRUE)) {
    devtools::build_readme(path, quiet = TRUE)
  } else stop("neither rmarkdown with pkgload nor devtools is installed")
}

# A package skeleton without usethis::create_package(), which refuses to run
# non interactively inside another project. desc writes the DESCRIPTION.
create_skeleton <- function(path, name, m, authors, org) {
  dir.create(file.path(path, "R"), recursive = TRUE, showWarnings = FALSE)
  d <- desc::description$new("!new")
  d$set(Package = name, Title = m$title, Description = m$description, Version = "0.0.0.9000",
        License = "CC BY 4.0", Encoding = "UTF-8", LazyData = "true", Roxygen = "list(markdown = TRUE)",
        URL = sprintf("https://github.com/%s/%s", org, name),
        BugReports = sprintf("https://github.com/%s/%s/issues", org, name),
        `X-schema.org-keywords` = paste(c("open data", "washdata", m$country, unlist(m$keywords)), collapse = ", "),
        `X-schema.org-spatialCoverage` = m$country)
  if (!is.null(m$collection_period)) d$set(`X-schema.org-temporalCoverage` = m$collection_period)
  d$set_authors(authors)
  d$write(file = file.path(path, "DESCRIPTION"))
  writeLines("# Generated by roxygen2: do not edit by hand", file.path(path, "NAMESPACE"))
  writeLines(c("^.*\\.Rproj$", "^\\.Rproj\\.user$", "^data-raw$", "^review$", "^build$", "^paper$", "^\\.github$",
               "^_pkgdown\\.yml$", "^docs$", "^pkgdown$", "^README\\.Rmd$", "^LICENSE\\.md$"), file.path(path, ".Rbuildignore"))
  invisible(path)
}
